-- Handling Missing Values and Outliers
/* Impute mean for the following columns, and round off to the nearest integer if required: WarehouseToHome,
 HourSpendOnApp, OrderAmountHikeFromlastYear,DaySinceLastOrder.*/
 -- WAREHOUSETOHOME
UPDATE CUSTOMER_CHURN C
CROSS JOIN (
    SELECT ROUND(AVG(WAREHOUSETOHOME)) AS MEAN_VALUE
    FROM CUSTOMER_CHURN
) M
SET C.WAREHOUSETOHOME = M.MEAN_VALUE
WHERE C.WAREHOUSETOHOME IS NULL;

-- HOURSPENDONAPP
