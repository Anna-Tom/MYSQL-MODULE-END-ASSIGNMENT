 -- Impute mode for the following columns: Tenure, CouponUsed, OrderCount.
 -- TENURE
 UPDATE CUSTOMER_CHURN C
CROSS JOIN (
    SELECT TENURE AS MODE_VALUE 
    FROM CUSTOMER_CHURN
    WHERE TENURE IS NOT NULL
    GROUP BY TENURE 
    ORDER BY COUNT(*) DESC 
    LIMIT 1
)  M
SET C.TENURE = M.MODE_VALUE
WHERE C.TENURE IS NULL;

-- COUPONUSED
UPDATE CUSTOMER_CHURN  C
CROSS JOIN (
    SELECT COUPONUSED AS MODE_VALUE 
    FROM CUSTOMER_CHURN
    WHERE COUPONUSED IS NOT NULL
    GROUP BY COUPONUSED 
    ORDER BY COUNT(*) DESC 
    LIMIT 1
)  M
SET C.COUPONUSED = M.MODE_VALUE
WHERE C.COUPONUSED IS NULL;

-- ORDERCOUNT
UPDATE CUSTOMER_CHURN C
CROSS JOIN (
    SELECT ORDERCOUNT AS MODE_VALUE 
    FROM CUSTOMER_CHURN
    WHERE ORDERCOUNT IS NOT NULL
    GROUP BY ORDERCOUNT 
    ORDER BY COUNT(*) DESC 
    LIMIT 1
)  M
SET C.ORDERCOUNT = M.MODE_VALUE
WHERE C.ORDERCOUNT IS NULL;

